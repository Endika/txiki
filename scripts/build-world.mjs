// Usage: node scripts/build-world.mjs
// Converts Natural Earth 1:110m (public domain, via world-atlas) into src/world-data.ts.
import { readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { feature } from 'topojson-client'
import countries from 'i18n-iso-countries'

const require = createRequire(import.meta.url)
const OUT = new URL('../src/world-data.ts', import.meta.url)
const TOPO = require.resolve('world-atlas/countries-110m.json')

const MIN_LAT = -60
const MAX_LAT = 84
const EXTRA = { Kosovo: 'XK' }
const DROP = new Set(['AQ'])

const round = (n) => Math.round(n * 10) / 10
const fmt = (n) => {
  const s = String(Object.is(n, -0) ? 0 : n)
  return s.replace(/^(-?)0\./, '$1.')
}
const join = (a, b) => (b.startsWith('-') ? a + b : `${a} ${b}`)

const TOLERANCE = 0.1
const isStraight = (a, b, c) => {
  const [dx, dy] = [c[0] - a[0], c[1] - a[1]]
  const len = Math.hypot(dx, dy)
  const dist = Math.abs(dx * (b[1] - a[1]) - dy * (b[0] - a[0])) / len
  const along = ((b[0] - a[0]) * dx + (b[1] - a[1]) * dy) / (len * len)
  return len > 0 && dist <= TOLERANCE && along > 0 && along < 1
}

function ringPath(ring) {
  const pts = []
  let prev = null
  for (const [lon0, lat] of ring) {
    let lon = lon0
    if (prev !== null) {
      while (lon - prev > 180) lon -= 360
      while (prev - lon > 180) lon += 360
    }
    prev = lon
    const p = [round(lon), round(-lat)]
    const last = pts[pts.length - 1]
    if (last && last[0] === p[0] && last[1] === p[1]) continue
    const before = pts[pts.length - 2]
    if (before && isStraight(before, last, p)) pts[pts.length - 1] = p
    else pts.push(p)
  }
  const first = pts[0]
  const end = pts[pts.length - 1]
  if (pts.length > 1 && first[0] === end[0] && first[1] === end[1]) pts.pop()
  if (pts.length < 3) return null
  let d = `M${join(fmt(pts[0][0]), fmt(pts[0][1]))}l`
  for (let i = 1; i < pts.length; i++) {
    const dx = round(pts[i][0] - pts[i - 1][0])
    const dy = round(pts[i][1] - pts[i - 1][1])
    if (Math.abs(dx) > 180) throw new Error(`antimeridian ${pts[i - 1]} -> ${pts[i]}`)
    const pair = join(fmt(dx), fmt(dy))
    d += pair.startsWith('-') || d.endsWith('l') ? pair : ` ${pair}`
  }
  return `${d}Z`
}

const topo = JSON.parse(await readFile(TOPO, 'utf8'))
const fc = feature(topo, topo.objects.countries)

const byCode = new Map()
for (const f of fc.features) {
  const code =
    EXTRA[f.properties?.name] ?? (f.id === undefined ? undefined : countries.numericToAlpha2(f.id))
  if (!code || DROP.has(code)) continue
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates
  const parts = polys.flatMap((poly) => poly.map(ringPath).filter(Boolean))
  if (parts.length === 0) continue
  byCode.set(code, (byCode.get(code) ?? '') + parts.join(''))
}

const list = [...byCode.entries()]
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  .map(([code, d]) => ({ code, d }))
const viewBox = [-180, -MAX_LAT, 360, MAX_LAT - MIN_LAT]

const body = `// Generated by scripts/build-world.mjs from Natural Earth (public domain) via world-atlas. Do not edit.
import type { World } from './map'

export const WORLD: World = {
  viewBox: ${JSON.stringify(viewBox)},
  countries: [${list.map((c) => `{code:'${c.code}',d:'${c.d}'}`).join(',')}],
}
`
await writeFile(OUT, body)
console.log(`wrote ${OUT.pathname}: ${list.length} countries, ${body.length} bytes`)
